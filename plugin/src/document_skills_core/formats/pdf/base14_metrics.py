def base14_text_width(text: str, font_size: float, resource: str) -> float:
    """Return Helvetica advance width, conservatively bounding unknown glyphs."""
    widths = _BOLD if resource in {"F2", "F4", "/F2", "/F4"} else _NORMAL
    return sum(widths.get(character, 1000) for character in text) * font_size / 1000.0


def base14_glyph_width(character: str, font_size: float, resource: str) -> float:
    return base14_text_width(character, font_size, resource)
